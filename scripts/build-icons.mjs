// Turns assets/* into src/icons.js (data URIs), so products need no extra image files or hosting.
// Run after changing an icon: npm run icons
import { readFileSync, writeFileSync, readdirSync } from "node:fs"
const dir = new URL("../assets/", import.meta.url)
const types = { png: "image/png", svg: "image/svg+xml" }
const lines = readdirSync(dir).sort().map((f) => {
  const [id, ext] = f.split(".")
  const data = readFileSync(new URL(f, dir)).toString("base64")
  return `  ${JSON.stringify(id)}: "data:${types[ext]};base64,${data}",`
})
writeFileSync(new URL("../src/icons.js", import.meta.url),
  `// Generated by scripts/build-icons.mjs from assets/. Do not edit by hand.\nexport const ICONS = {\n${lines.join("\n")}\n}\n`)
console.log(`wrote ${lines.length} icons`)
